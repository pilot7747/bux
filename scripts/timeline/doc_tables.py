def report_tables(text: str) -> dict[str, list[list[str]]]:
    """Each section's first table by its heading, as rows of cells, the header first."""
    out: dict[str, list[list[str]]] = {}
    title, done = "", set()
    for line in text.splitlines():
        if line.startswith("## "):
            title = line[3:].strip()
        elif not line.startswith("|"):
            done |= {title} & out.keys()
        elif title not in done and not set(line.strip()) <= set("|-: "):
            out.setdefault(title, []).append(
                [c.strip() for c in line.strip().strip("|").split("|")]
            )
    return out


def factorial_tables(text: str) -> dict[str, list[list[str]]]:
    """factorial.py's main effects of each metric: term, effect, se, t."""
    out: dict[str, list[list[str]]] = {}
    metric, inside = "", False
    effect = re.compile(r"\s+(\w+)\s+([+-][\d.]+)\s+([\d.]+)\s+([+-][\d.]+)")
    for line in text.splitlines():
        if m := re.match(r"## (\w+):", line):
            metric, inside = m.group(1), False
        elif line.startswith("Main effects"):
            inside, out[metric] = True, [["term", "effect %", "se", "t"]]
        elif inside and (m := effect.match(line)):
            out[metric].append(list(m.groups()))
        elif inside and line.strip() and not line.startswith("  term"):
            inside = False
    return out


def section(tables: dict, prefix: str) -> list[list[str]]:
    """The table of the first section whose heading starts with `prefix`."""
    if not prefix:
        return next(iter(tables.values()))
    for title, rows in tables.items():
        if title.startswith(prefix):
            return rows
    sys.exit(f"no section {prefix!r} in the source")


def by_key(rows: list[list[str]], key: int) -> tuple[list[str], dict]:
    """A section's header and its rows by key, the first of each: some repeat."""
    found: dict = {}
    for r in rows[1:]:
        found.setdefault(r[0] if key == 1 else tuple(r[:key]), r)
    return rows[0], found


def cell(header: list[str], row: list[str] | None, c: Col, where: str) -> str:
    if row is None:
        return ""
    if c.header not in header:
        print(f"warning: no column {c.header!r} in {where!r}", file=sys.stderr)
        return ""
    v = row[header.index(c.header)]
    v = NAMES.get(v, v) if c.header == "vs" else v
    return v if c.ranges else RANGE.sub("", v)


def render(t: Table, tables: dict) -> str:
    """`t` as Markdown, from the sections of its source."""
    names = {t.section, *(c.section for c in t.columns if c.section)}
    sections = {s: by_key(section(tables, s), t.key) for s in names}
    lines = [
        "| | " + " | ".join(c.label for c in t.columns) + " |",
        "|---" * (len(t.columns) + 1) + "|",
    ]
    for key, name in t.rows:
        cells = []
        for c in t.columns:
            header, found = sections[c.section or t.section]
            row = found.get(key)
            if row is None:
                print(
                    f"warning: no row {key!r} in {c.section or t.section!r}",
                    file=sys.stderr,
                )
            elif (
                t.against
                and c.section == LEADER
                and row[header.index("vs")] != t.against
            ):
                row = None
            cells.append(cell(header, row, c, c.section or t.section))
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def board(tables: dict) -> str:
    """Every row of the one-change leaderboard."""
    header, found = by_key(section(tables, LEADER), 1)
    lines = [
        "| family | " + " | ".join(c.label for c in BOARD) + " |",
        "|---" * (len(BOARD) + 1) + "|",
    ]
    for family, row in found.items():
        cells = " | ".join(cell(header, row, c, LEADER) for c in BOARD)
        lines.append(f"| `{family}` | {cells} |")
    return "\n".join(lines) + "\n"


PENDING = ":::{note}\nThe FP8 targets are not measured yet.\n:::\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("report", type=Path, help="fit.py's report.md")
    p.add_argument(
        "serving", type=Path, help="sweep_fit.py's serving-measured.md, bf16"
    )
    p.add_argument("factorial", type=Path, help="factorial.py's output")
    p.add_argument("--fp8", type=Path, help="sweep_fit.py's serving-measured.md, FP8")
    p.add_argument("--out", type=Path, default=OUT)
    a = p.parse_args()
    sources = {
        "report": report_tables(a.report.read_text()),
        "serving": report_tables(a.serving.read_text()),
        "factorial": factorial_tables(a.factorial.read_text()),
    }
    if a.fp8:
        sources["fp8"] = report_tables(a.fp8.read_text())
    a.out.mkdir(parents=True, exist_ok=True)
    for name, t in TABLES.items():
        text = render(t, sources[t.source]) if t.source in sources else PENDING
        (a.out / f"{name}.md").write_text(HEADER + text)
    (a.out / "leaderboard.md").write_text(HEADER + board(sources["report"]))
    print(f"{len(TABLES) + 1} tables in {a.out}")


if __name__ == "__main__":
    main()
